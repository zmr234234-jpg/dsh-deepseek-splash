/**
 * Checks the host half without an Electron install and without booting DSH.
 *
 * The interesting behaviour is the reinstall after a desktop update: it has to
 * replace a stock page, keep the shell's page as a backup exactly once, skip
 * when the page is already ours, and stay out of the way when the user revoked
 * it. Every case runs against a throwaway directory.
 *
 * Run: node tools/smoke_host.mjs
 */
import assert from 'node:assert/strict'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { apply, installLaunchScreen, resolveResources } from '../lib/index.js'

const MARKER = 'dsh-deepseek-splash: launch screen'
const checks = []

function check(label, fn) {
  fn()
  checks.push(label)
  console.log(`ok   ${label}`)
}

function sandbox() {
  const root = mkdtempSync(join(tmpdir(), 'dss-host-'))
  const resources = join(root, 'DSH Desktop', 'resources')
  mkdirSync(resources, { recursive: true })
  mkdirSync(join(root, 'pkg', 'dist'), { recursive: true })
  writeFileSync(
    join(root, 'pkg', 'dist', 'splash.html'),
    `<!doctype html>\n<!-- ${MARKER}. Generated by tools/build_splash.py -->\n<html><body>ours</body></html>\n`,
    'utf8'
  )
  return { root, resources, target: join(resources, 'splash.html'), pkg: join(root, 'pkg') }
}

const STOCK = '<!doctype html><html><body><img id="logo" src="dsh-loader.gif"></body></html>'
const cases = []
const cleanup = () => {
  for (const dir of cases) rmSync(dir, { recursive: true, force: true })
}
process.on('exit', cleanup)

function fresh(stock = STOCK) {
  const box = sandbox()
  cases.push(box.root)
  // `stock: false` means "this install ships no launch screen at all".
  if (stock !== false) writeFileSync(box.target, stock, 'utf8')
  return box
}

check('resolveResources prefers an explicit resourcesPath', () => {
  const box = fresh()
  assert.equal(resolveResources('ignored/DSH Desktop.exe', box.resources), box.resources)
})

check('resolveResources falls back to <exe>/resources', () => {
  const box = fresh()
  const exe = join(box.resources, '..', 'DSH Desktop.exe')
  assert.equal(resolveResources(exe, null), box.resources)
})

check('no desktop install means skip', () => {
  const box = fresh()
  const result = installLaunchScreen({ root: box.pkg, resources: null, execPath: 'nowhere', resourcesPath: null })
  assert.equal(result.status, 'skip')
  assert.equal(result.reason, 'not-a-desktop-install')
  assert.equal(existsSync(box.target), true, 'and it must not touch another install')
})

check('a stock page is replaced and kept as the backup', () => {
  const box = fresh()
  const result = installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(result.status, 'installed')
  assert.equal(readFileSync(box.target, 'utf8'), readFileSync(join(box.pkg, 'dist', 'splash.html'), 'utf8'))
  assert.equal(readFileSync(box.target + '.dsh-deepseek-splash.bak', 'utf8'), STOCK)
})

check('a second boot is a no-op', () => {
  const box = fresh()
  installLaunchScreen({ root: box.pkg, resources: box.resources })
  const again = installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(again.status, 'unchanged')
  assert.equal(readFileSync(box.target + '.dsh-deepseek-splash.bak', 'utf8'), STOCK)
})

check('an updated shell page never replaces the pristine backup', () => {
  const box = fresh()
  installLaunchScreen({ root: box.pkg, resources: box.resources })
  writeFileSync(box.target, '<!doctype html><html><body>stock vNext</body></html>', 'utf8')
  const result = installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(result.status, 'installed')
  assert.equal(readFileSync(box.target + '.dsh-deepseek-splash.bak', 'utf8'), STOCK)
})

check('the revoke marker stops the reinstall', () => {
  const box = fresh()
  writeFileSync(box.target + '.dsh-deepseek-splash.revoked', `${MARKER}: revoked\n`, 'utf8')
  const result = installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(result.status, 'skip')
  assert.equal(result.reason, 'revoked')
  assert.equal(readFileSync(box.target, 'utf8'), STOCK)
})

check('a shell without a launch screen is left alone', () => {
  const box = fresh(false)
  const result = installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(result.status, 'skip')
  assert.equal(result.reason, 'no-launcher-splash')
})

check('a missing payload is reported, not thrown', () => {
  const box = fresh()
  const result = installLaunchScreen({ root: join(box.root, 'empty'), resources: box.resources })
  assert.equal(result.status, 'skip')
  assert.equal(result.reason, 'no-rendered-page')
})

check('a payload without the marker is refused', () => {
  const box = fresh()
  writeFileSync(join(box.pkg, 'dist', 'splash.html'), '<!doctype html><html><body>bye</body></html>', 'utf8')
  const result = installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(result.status, 'skip')
  assert.equal(result.reason, 'rendered-page-without-marker')
})

check('installing leaves no staging file behind', () => {
  const box = fresh()
  installLaunchScreen({ root: box.pkg, resources: box.resources })
  assert.equal(existsSync(box.target + '.dsh-deepseek-splash.tmp'), false)
})

check('apply() never throws when the plugin context is bare', () => {
  apply(undefined)
})

console.log(`\nall ${checks.length} checks passed`)
