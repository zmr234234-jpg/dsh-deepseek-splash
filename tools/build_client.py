"""Assemble the dsh-deepseek-splash client bundle and its preview page.

Inputs :  assets/whale.svg (tools/trace_whale.py), src/splash.css,
          src/splash.js, src/overlay.js
Outputs:  lib/client.js    -> window.__ModuleLoader__.load({ id, factory })
          assets/preview.html -> standalone page that plays the same animation

Run:  python tools/build_client.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = "dsh-deepseek-splash"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return fh.read()


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return len(text.encode("utf-8"))


def js_string(value):
    """JSON is a valid JS string literal for our payloads (no U+2028/2029)."""
    return json.dumps(value, ensure_ascii=False)


def whale_svg():
    """The traced mark, carrying the gradient definitions the CSS fills use."""
    whale = read("assets/whale.svg").strip()

    for needle in ("</script", "<!--"):
        if needle in whale:
            raise SystemExit("whale.svg contains %r; refusing to inline" % needle)

    # Ship the mark's gradients with the artwork so the fill can be a brushed
    # white->pale-blue sweep instead of a flat plate of colour.
    gradients = (
        '<defs>'
        '<linearGradient id="dssFillDark" x1="0" y1="0" x2=".4" y2="1">'
        '<stop offset="0" stop-color="#ffffff"/>'
        '<stop offset="1" stop-color="#d2dfff"/>'
        '</linearGradient>'
        '<linearGradient id="dssFillLight" x1="0" y1="0" x2=".4" y2="1">'
        '<stop offset="0" stop-color="#1d2949"/>'
        '<stop offset="1" stop-color="#0a1124"/>'
        '</linearGradient>'
        '</defs>'
    )
    head_end = whale.index(">") + 1
    return whale[:head_end] + gradients + whale[head_end:]


def main():
    css = read("src/splash.css")
    runtime = read("src/splash.js")
    overlay = read("src/overlay.js")
    whale = whale_svg()

    client = "\n".join([
        "// %s - client half. Generated by tools/build_client.py; edit src/* instead." % PKG,
        "window.__ModuleLoader__.load({",
        '  id: "%s",' % PKG,
        "  factory: (require) => {",
        "    var module = { exports: {} }, exports = module.exports;",
        '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
        '    const React = require("react");',
        "    const CSS_TEXT = %s;" % js_string(css),
        "    const WHALE_SVG = %s;" % js_string(whale),
        "",
        runtime.strip(),
        "",
        overlay.strip(),
        "",
        "    return exports;",
        "  },",
        "});",
        "",
    ])
    client_bytes = write("lib/client.js", client)

    preview = "\n".join([
        "<!doctype html>",
        '<html lang="zh-CN" data-theme="dark">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>DeepSeek 开屏动画 · 预览</title>",
        "<style>",
        "html,body{margin:0;height:100%;background:#05070e;font-family:'Segoe UI',system-ui,sans-serif;color:#e8eeff}",
        "html[data-theme=light],html[data-theme=light] body{background:#eef2fb;color:#101a33}",
        "#bar{position:fixed;left:12px;bottom:12px;z-index:2147483600;display:flex;gap:8px;align-items:center;",
        "     font-size:12px;letter-spacing:.04em}",
        "#bar button{font:inherit;padding:6px 12px;border-radius:999px;cursor:pointer;",
        "            border:1px solid currentColor;background:transparent;color:inherit;opacity:.55}",
        "#bar button:hover{opacity:1}",
        "</style>",
        "</head>",
        "<body>",
        '<div id="stage"></div>',
        '<div id="bar"><button id="again">重播</button><button id="theme">切换深浅色</button></div>',
        "<script>",
        "const CSS_TEXT = %s;" % js_string(css),
        "const WHALE_SVG = %s;" % js_string(whale),
        "(function(){var s=document.createElement('style');s.textContent=CSS_TEXT;document.head.appendChild(s);})();",
        runtime.strip(),
        "var stage = document.getElementById('stage');",
        "var handle = null;",
        "function play(opts) {",
        "  if (handle) handle.destroy();",
        "  handle = mountSplash(stage, opts || {});",
        "}",
        "/* #t=1200 freezes every animation at that millisecond (frame inspection) */",
        "var frameMs = parseFloat((location.hash.match(/t=([0-9.]+)/) || [])[1]);",
        "if (!isNaN(frameMs)) {",
        "  play({ holdMs: 1e9 });",
        "  requestAnimationFrame(function () {",
        "    document.getAnimations().forEach(function (a) { a.pause(); a.currentTime = frameMs; });",
        "  });",
        "} else {",
        "  play({});",
        "}",
        "document.getElementById('again').onclick = function () { play({}); };",
        "document.getElementById('theme').onclick = function () {",
        "  var el = document.documentElement;",
        "  el.dataset.theme = el.dataset.theme === 'light' ? 'dark' : 'light';",
        "  play({ holdMs: isNaN(frameMs) ? undefined : 1e9 });",
        "  if (!isNaN(frameMs)) {",
        "    requestAnimationFrame(function () {",
        "      document.getAnimations().forEach(function (a) { a.pause(); a.currentTime = frameMs; });",
        "    });",
        "  }",
        "};",
        "</script>",
        "</body>",
        "</html>",
        "",
    ])
    preview_bytes = write("assets/preview.html", preview)

    print("lib/client.js      %7d bytes" % client_bytes)
    print("assets/preview.html %6d bytes" % preview_bytes)
    print("whale.svg          %7d bytes" % len(whale.encode("utf-8")))


if __name__ == "__main__":
    main()
